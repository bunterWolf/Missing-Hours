#!/usr/bin/env node
/*
 * Site checks: node _design/check.mjs
 * Reads the built pages as text and asserts structure, copy rules, assets and SEO data.
 * Each check returns a list of problems; an empty list passes. Exit code 1 if any check fails.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => fs.readFileSync(path.join(root, p), 'utf8');
const exists = (p) => fs.existsSync(path.join(root, p));
const PAGES = ['index.html', '404.html', 'imprint/index.html', 'privacy/index.html'];

const checks = [];
const check = (name, fn) => checks.push({ name, fn });

// All URLs a page references through src, href and srcset.
function refs(html) {
  const out = [];
  for (const m of html.matchAll(/\s(src|href)="([^"]*)"/g)) out.push(m[2]);
  for (const m of html.matchAll(/\ssrcset="([^"]*)"/g)) {
    for (const part of m[1].split(',')) out.push(part.trim().split(/\s+/)[0]);
  }
  return out;
}

// Resolves a local reference from a page to a repo path, or null for external/anchor refs.
function localPath(page, ref, base = '') {
  if (!ref || /^(https?:|mailto:|tel:|data:|#)/.test(ref)) return null;
  let p = ref.split(/[?#]/)[0];
  if (!p) return null;
  p = p.startsWith('/') ? p.slice(1) : path.posix.join(path.posix.dirname(page), p);
  if (p === '' || p === '.' || p.endsWith('/')) p = path.posix.join(p, 'index.html');
  return path.posix.join(base, p);
}

check('assets exist', () => {
  const problems = [];
  for (const page of PAGES) {
    for (const ref of refs(read(page))) {
      const p = localPath(page, ref);
      if (p && !exists(p)) problems.push(`${page}: ${ref} -> ${p} missing`);
    }
  }
  return problems;
});

check('no design syntax', () => {
  // data-dc attributes hold the runtime's own {{ }} templates on purpose.
  const m = read('index.html').replace(/data-dc='[^']*'/g, '').match(/\{\{|<\/?sc-|<\/?dc-|\/_blob\//);
  return m ? [`index.html contains ${m[0]}`] : [];
});

check('downloads have fallback', () => {
  const problems = [];
  const tags = read('index.html').match(/<a\b[^>]*\bdata-download\b[^>]*>/g) || [];
  if (!tags.length) problems.push('no a[data-download] found');
  for (const tag of tags) {
    const href = (tag.match(/\shref="([^"]*)"/) || [])[1] || '';
    if (!/\/releases\/download\/v\d+\.\d+\.\d+\/Missing-Hours-Setup-\d+\.\d+\.\d+-win-x64\.exe$/.test(href)) {
      problems.push(`download link without installer fallback: ${tag.slice(0, 120)}`);
    }
  }
  return problems;
});

check('external origins', () => {
  const problems = [];
  for (const page of PAGES) {
    for (const m of read(page).matchAll(/\ssrc="(https?:[^"]*)"/g)) problems.push(`${page}: external src ${m[1]}`);
  }
  for (const f of fs.readdirSync(path.join(root, 'assets')).filter((f) => f.endsWith('.js'))) {
    for (const m of read(`assets/${f}`).matchAll(/fetch\(\s*['"`]([^'"`]+)/g)) {
      if (!m[1].startsWith('https://api.github.com/')) problems.push(`assets/${f}: fetch ${m[1]}`);
    }
  }
  return problems;
});

check('no generated banner', () =>
  ['index.html', 'assets/site.css', 'assets/design.js']
    .filter((f) => read(f).includes('Generated by _design/build.mjs'))
    .map((f) => `${f} still says it is generated`));

check('preview build', () => {
  if (!exists('.preview/index.html')) return [];
  const html = read('.preview/index.html');
  const problems = [];
  const m = html.match(/<!doctype|<html\b|<head\b|<body\b/i);
  if (m) problems.push(`preview still contains ${m[0]}`);
  if (!/<title>[^<]+<\/title>/.test(html)) problems.push('preview has no <title>');
  for (const ref of refs(html)) {
    const p = localPath('index.html', ref, '.preview');
    if (p && !exists(p)) problems.push(`preview: ${ref} -> ${p} missing`);
  }
  return problems;
});

check('new logo', () => {
  const problems = [];
  const dark = /<source srcset="[^"]*logo-dark[^"]*\.svg" media="\(prefers-color-scheme: dark\)">\s*<img src="[^"]*logo-light[^"]*\.svg"/g;
  for (const page of PAGES) {
    const html = read(page);
    if (/[/"]icon\.(svg|png)/.test(html)) problems.push(`${page} still references the old icon`);
    const header = (html.match(/<header[\s\S]*?<\/header>/) || [''])[0];
    const footer = (html.match(/<footer[\s\S]*?<\/footer>/) || [''])[0];
    if (!header.match(dark)) problems.push(`${page}: header has no light/dark logo`);
    if (!footer.match(dark)) problems.push(`${page}: footer has no light/dark logo`);
    if (!/<link rel="icon" href="[^"]*favicon\.svg" type="image\/svg\+xml">/.test(html)) problems.push(`${page}: no SVG favicon`);
    if (!/<link rel="apple-touch-icon" href="[^"]*apple-touch-icon\.png">/.test(html)) problems.push(`${page}: no apple-touch-icon`);
  }
  const fav = exists('assets/favicon.svg') ? read('assets/favicon.svg') : '';
  if (!/prefers-color-scheme: ?dark/.test(fav)) problems.push('assets/favicon.svg has no dark-mode style');
  if (!fav.includes('#e5484d')) problems.push('assets/favicon.svg lost the red hour');
  return problems;
});

const SECTIONS = [
  ['top', null],
  ['cost', 'Forgotten hours cost real money.'],
  ['how', 'How automatic time tracking works here'],
  ['example', 'From your day to your timesheet'],
  ['records', 'What it records, and what it never does'],
  ['any-day', 'Any day, rough or precise.'],
  ['alongside', 'Keep your time tracker. This is where you look things up.'],
  ['privacy', 'No account. No cloud.'],
  ['free', 'Free, with the code in the open.'],
  ['faq', 'Questions'],
  ['download', 'What did you work on last Tuesday?']
];
const text = (s) => s.replace(/<[^>]+>/g, '').replace(/&#39;/g, "'").replace(/&amp;/g, '&').trim();

check('structure', () => {
  const html = read('index.html');
  const problems = [];
  const h1s = html.match(/<h1\b[^>]*>[\s\S]*?<\/h1>/g) || [];
  if (h1s.length !== 1 || text(h1s[0]) !== 'Find your missing hours.') problems.push(`expected one H1 "Find your missing hours.", found ${h1s.length}`);
  const sections = [...html.matchAll(/<section\b[^>]*\bid="([^"]+)"[^>]*>([\s\S]*?)<\/section>/g)].map((m) => [m[1], m[2]]);
  const ids = sections.map((s) => s[0]);
  const want = SECTIONS.map((s) => s[0]);
  if (ids.join() !== want.join()) problems.push(`section order\n      is   ${ids.join(' ')}\n      want ${want.join(' ')}`);
  for (const [id, h2] of SECTIONS) {
    if (!h2) continue;
    const body = (sections.find((s) => s[0] === id) || [])[1] || '';
    const got = (body.match(/<h2\b[^>]*>([\s\S]*?)<\/h2>/) || [])[1];
    if (!got || text(got) !== h2) problems.push(`#${id}: H2 is "${got ? text(got) : 'missing'}", want "${h2}"`);
  }
  if ((html.match(/<section\b/g) || []).length !== SECTIONS.length) problems.push('there are sections without the expected ids');
  return problems;
});

check('copy rules', () => {
  const html = text(read('index.html'));
  const problems = [];
  for (const bad of ['It just runs along', 'Running a team', "Breaks don't count as work", 'open source', 'Open source',
    'Signed installer', 'add up on their own', 'Fill a timesheet', 'Answer a client', 'Find a lost hour', 'Write an invoice']) {
    if (html.includes(bad)) problems.push(`must not say "${bad}"`);
  }
  for (const good of ['Automatic time tracking for Windows', 'keystrokes', 'window title', 'Microsoft Store', '30 days']) {
    if (!html.toLowerCase().includes(good.toLowerCase())) problems.push(`should say "${good}"`);
  }
  return problems;
});

check('no dangling bindings', async () => {
  const vm = await import('node:vm');
  const ctx = { window: {} };
  vm.createContext(ctx);
  vm.runInContext(read('assets/design.js'), ctx);
  class DCLogic { constructor() { this.props = {}; this.state = {}; } }
  const vals = new (ctx.window.MHDesign(DCLogic))().renderVals();
  const get = (p) => p.split('.').reduce((v, k) => (v == null ? undefined : v[k]), vals);
  const html = read('index.html');
  const paths = new Set();
  for (const m of html.matchAll(/data-dc-(?:text|if)="([^"]+)"/g)) paths.add(m[1]);
  for (const m of html.matchAll(/data-dc='([^']*)'/g)) for (const h of m[1].matchAll(/\{\{\s*([\w.$]+)\s*\}\}/g)) paths.add(h[1]);
  for (const m of html.matchAll(/data-dc-on='([^']*)'/g)) for (const p of Object.values(JSON.parse(m[1]))) paths.add(p);
  return [...paths].filter((p) => get(p) === undefined).map((p) => `binding ${p} has no value in renderVals()`);
});

const SEO_TITLE = 'Missing Hours – Automatic time tracking for Windows, free and private';
const SEO_DESC = 'Automatic time tracking for Windows. Missing Hours notes which app and window you work in, so you can fill in your timesheet without guessing. Free, no account, stays on your PC.';
const FAQ = [
  'What is automatic time tracking?',
  'Does Missing Hours record keystrokes or take screenshots?',
  'Does it work with Toggl, Harvest or Clockify?',
  'Can my employer see what I do?',
  'Is it free? Does it run on Mac?'
];
const attr = (html, re) => (html.match(re) || [])[1];

check('seo head', () => {
  const html = read('index.html');
  const problems = [];
  if (attr(html, /<title>([^<]*)<\/title>/) !== SEO_TITLE) problems.push('title');
  if (attr(html, /<meta name="description" content="([^"]*)">/) !== SEO_DESC) problems.push('meta description');
  if (attr(html, /<link rel="canonical" href="([^"]*)">/) !== 'https://missing-hours.app/') problems.push('canonical');
  if (attr(html, /<meta property="og:title" content="([^"]*)">/) !== SEO_TITLE) problems.push('og:title');
  if (attr(html, /<meta property="og:description" content="([^"]*)">/) !== SEO_DESC) problems.push('og:description');
  if (attr(html, /<meta name="twitter:card" content="([^"]*)">/) !== 'summary_large_image') problems.push('twitter:card');
  if (attr(html, /<meta property="og:image" content="([^"]*)">/) !== 'https://missing-hours.app/assets/og.png') problems.push('og:image url');
  if (!exists('assets/og.png')) problems.push('assets/og.png missing');
  else {
    const b = fs.readFileSync(path.join(root, 'assets/og.png'));
    const w = b.readUInt32BE(16), h = b.readUInt32BE(20);
    if (b.toString('ascii', 1, 4) !== 'PNG' || w !== 1200 || h !== 630) problems.push(`og.png is ${w}x${h}, want a 1200x630 PNG`);
  }
  return problems;
});

check('json-ld', () => {
  const html = read('index.html');
  const problems = [];
  const blocks = [...html.matchAll(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/g)].map((m) => JSON.parse(m[1]));
  const app = blocks.find((b) => b['@type'] === 'SoftwareApplication');
  const faq = blocks.find((b) => b['@type'] === 'FAQPage');
  if (!app) problems.push('no SoftwareApplication');
  else {
    if (app.name !== 'Missing Hours' || app.operatingSystem !== 'Windows 10, Windows 11') problems.push('SoftwareApplication name/operatingSystem');
    if (!app.offers || String(app.offers.price) !== '0') problems.push('SoftwareApplication price');
    const dl = (html.match(/<a\b[^>]*\bdata-download\b[^>]*>/) || [''])[0].match(/href="([^"]*)"/);
    if (!dl || app.downloadUrl !== dl[1]) problems.push('SoftwareApplication downloadUrl differs from the download button');
  }
  if (!faq) problems.push('no FAQPage');
  else {
    const qs = faq.mainEntity.map((q) => q.name);
    if (qs.join('|') !== FAQ.join('|')) problems.push('FAQPage questions differ from the plan');
    const faqHtml = (html.match(/<section\b[^>]*id="faq"[^>]*>([\s\S]*?)<\/section>/) || [])[1] || '';
    const summaries = [...faqHtml.matchAll(/<summary>([\s\S]*?)<\/summary>/g)].map((m) => text(m[1]));
    const answers = [...faqHtml.matchAll(/<\/summary>([\s\S]*?)<\/details>/g)].map((m) => text(m[1]));
    if (summaries.join('|') !== qs.join('|')) problems.push('visible FAQ questions differ from FAQPage');
    faq.mainEntity.forEach((q, i) => { if (q.acceptedAnswer.text !== answers[i]) problems.push(`FAQ answer ${i + 1} differs from the page`); });
    if ((faqHtml.match(/<details\b/g) || []).length !== FAQ.length) problems.push('FAQ needs one <details> per question');
  }
  return problems;
});

check('robots and sitemap', () => {
  const problems = [];
  if (!exists('robots.txt') || !read('robots.txt').includes('Sitemap: https://missing-hours.app/sitemap.xml')) problems.push('robots.txt');
  if (!exists('sitemap.xml')) return [...problems, 'sitemap.xml missing'];
  const urls = [...read('sitemap.xml').matchAll(/<loc>https:\/\/missing-hours\.app\/([^<]*)<\/loc>/g)].map((m) => m[1]);
  if (urls.join('|') !== '|privacy/') problems.push(`sitemap lists ${urls.join(', ')}`);
  for (const u of urls) if (!exists(u + 'index.html')) problems.push(`sitemap URL /${u} has no page`);
  return problems;
});

check('privacy wording', () => {
  const p = text(read('privacy/index.html'));
  return p.includes('Microsoft Store') ? [] : ['privacy page should explain the update check for both builds'];
});

// ---------------------------------------------------------------------------
let failed = 0;
for (const { name, fn } of checks) {
  let problems;
  try { problems = await fn(); } catch (e) { problems = [`threw: ${e.message}`]; }
  if (problems.length) {
    failed++;
    console.log(`FAIL ${name}`);
    for (const p of problems.slice(0, 20)) console.log(`  - ${p}`);
    if (problems.length > 20) console.log(`  … ${problems.length - 20} more`);
  }
}
if (failed) { console.log(`check: ${failed} of ${checks.length} failed`); process.exit(1); }
console.log(`check: ok (${checks.length} checks)`);
